export function createCores(count: number): CPUCore[] {
  const coreColors = ['#3b82f6', '#06b6d4', '#10b981', '#8b5cf6'];
  return Array.from({ length: count }, (_, i) => ({
    id: `CPU ${i}`,
    name: `CPU Core ${i}`,
    coreIndex: i,
    assignedProcessId: null,
    busyTicks: 0,
    contextSwitchTicks: 0,
    idleTicks: 0,
    isSwitching: false,
    contextSwitchRemaining: 0,
    switchingToProcessId: null,
    previousProcessId: null,
    color: coreColors[i % coreColors.length],
  }));
}

